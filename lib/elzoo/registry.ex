defmodule Elzoo.Registry do
  @moduledoc "Development-time piece inventory, validation and dependency selection."
  @kinds ~w(owned adapter recipe)
  @grounding ~w(proof type test upstream assumption monitor)
  @faces ~w(telemetry config control)

  def load!(root \\ File.cwd!()) do
    root = Path.expand(root)
    index = json!(root, "registry/catalogue.json")
    provider_file = json!(root, "registry/providers.json")
    version!(index)
    version!(provider_file)
    providers = Map.fetch!(provider_file, "providers")
    Enum.each(providers, &validate_provider!(root, &1))

    entries =
      Enum.map(Map.fetch!(index, "entries"), fn entry ->
        id!(entry["id"])

        if manifest = entry["manifest"] do
          piece = json!(root, manifest)
          version!(piece)
          ensure!(piece["id"] == entry["id"], "manifest ID mismatch: #{manifest}")
          validate_piece!(root, manifest, piece, providers)
          Map.merge(entry, piece) |> Map.put("directory", Path.dirname(manifest))
        else
          ensure!(entry["status"] in ~w(planned deferred), "invalid planned status: #{entry["id"]}")
          nonempty!(entry["reason"], "planned reason: #{entry["id"]}")
          entry
        end
      end)

    ensure!(length(entries) == length(Enum.uniq_by(entries, & &1["id"])), "duplicate catalogue ID")
    registry = %{root: root, entries: Map.new(entries, &{&1["id"], &1}), providers: providers}

    Enum.each(entries, fn entry ->
      if entry["status"] == "ready", do: select!(registry, [entry["id"]])
    end)

    registry
  end

  def select!(registry, ids) when is_list(ids) do
    ensure!(ids != [], "select at least one piece ID")

    {_, order} =
      Enum.reduce(Enum.sort(Enum.uniq(ids)), {MapSet.new(), []}, fn id, acc ->
        visit!(registry, id, [], acc)
      end)

    Enum.map(order, &Map.fetch!(registry.entries, &1))
  end

  def ledger(registry) do
    rows =
      registry.entries
      |> Map.values()
      |> Enum.sort_by(& &1["id"])
      |> Enum.map(fn entry ->
        if entry["status"] == "ready" do
          evidence =
            entry["grounding"]
            |> Enum.map(& &1["kind"])
            |> Enum.uniq()
            |> Enum.sort()
            |> Enum.join(", ")

          providers =
            Enum.map_join(entry["providers"], ", ", fn id ->
              "#{id} #{registry.providers[id]["version"]}"
            end)

          operations = Enum.map_join(@faces, "; ", &"#{&1}: #{entry["operations"][&1]["status"]}")

          "| [#{entry["id"]}](#{entry["directory"]}/README.md) | ready (subset) | #{entry["kind"]} | #{providers} | #{evidence} | #{operations} | #{cell(entry["contract"])} |"
        else
          "| `#{entry["id"]}` | #{entry["status"]} | #{entry["disposition"]} (planned) | — | none claimed | unassessed | #{cell(entry["reason"])} |"
        end
      end)

    """
    # Piece ledger

    Generated by `mix elzoo.ledger`; edit registry/catalogue.json,
    registry/providers.json or a piece.json, then regenerate. `mix check`
    rejects drift. Ready means the linked narrow contract is usable; it does
    not mean the entire capability family is implemented or universally proven.

    Owned = handwritten Elzoo implementation. Adapter = Elzoo translation around
    upstream behavior. Recipe = direct upstream API usage, with no production
    wrapper. Proof/type/test/upstream/assumption labels apply to individual
    claims in each piece.json. Assumptions are not evidence of correctness.

    Operational applicability is declared in each piece.json: supported here,
    inherited from a named provider/dependency, not_applicable (with reason),
    or planned (not supplied). It does not expose a network endpoint or add
    guarantees beyond the declared Contract. See docs/operational-contracts.md.

    | Piece | Status | Implementation | Direct providers | Grounding kinds | Operational applicability | Contract / remaining gap |
    | --- | --- | --- | --- | --- | --- | --- |
    #{Enum.join(rows, "\n")}
    """
  end

  def source!(root, relative) do
    relative!(relative)
    path = Path.join(root, relative)

    relative
    |> Path.split()
    |> Enum.reduce(root, fn segment, base ->
      next = Path.join(base, segment)

      case File.lstat(next) do
        {:ok, %{type: :symlink}} -> fail!("symlink source is not supported: #{relative}")
        {:ok, _} -> :ok
        {:error, reason} -> fail!("missing source #{relative}: #{reason}")
      end

      next
    end)

    ensure!(File.regular?(path), "not a regular source file: #{relative}")
    path
  end

  def relative!(path) do
    ensure!(
      is_binary(path) and path != "" and Path.type(path) == :relative and
        not String.contains?(path, ["\\", "\0"]) and
        Enum.all?(String.split(path, "/"), &(&1 not in ["", ".", ".."])),
      "unsafe relative path: #{inspect(path)}"
    )

    path
  end

  defp validate_piece!(root, manifest, piece, providers) do
    id = piece["id"]
    directory = Path.dirname(manifest)

    ensure!(
      directory == "pieces/#{id}" and Path.basename(manifest) == "piece.json",
      "noncanonical piece location: #{id}"
    )

    ensure!(piece["status"] == "ready", "source manifest must be ready: #{id}")
    ensure!(piece["kind"] in @kinds, "unknown implementation kind: #{id}")
    ensure!(piece["license"] == "Apache-2.0", "missing owned-source license: #{id}")
    ensure!(piece["coverage"] == "subset", "declare the scoped coverage: #{id}")
    nonempty!(piece["contract"], "contract: #{id}")
    ensure!(is_list(piece["limits"]) and piece["limits"] != [], "limits missing: #{id}")
    Enum.each(piece["limits"], &nonempty!(&1, "limit: #{id}"))
    ensure!(is_list(piece["dependencies"]), "dependencies missing: #{id}")
    Enum.each(piece["dependencies"], &id!/1)
    ensure!(is_list(piece["providers"]), "providers missing: #{id}")

    Enum.each(
      piece["providers"],
      &ensure!(Map.has_key?(providers, &1), "unknown provider #{&1}: #{id}")
    )

    validate_operations!(piece)

    applications = Map.get(piece, "applications", [])
    ensure!(is_list(applications), "invalid OTP applications: #{id}")

    Enum.each(applications, fn application ->
      ensure!(
        is_binary(application) and Regex.match?(~r/\A[a-z][a-z0-9_]*\z/, application),
        "invalid OTP application: #{id}"
      )
    end)

    source!(root, "#{directory}/README.md")
    files = piece["files"]

    ensure!(
      is_list(files) and files != [] and length(files) == length(Enum.uniq(files)),
      "files missing or duplicated: #{id}"
    )

    Enum.each(files, fn file ->
      relative!(file)

      ensure!(
        hd(Path.split(file)) in ~w(lib cure test examples),
        "unsupported source role: #{id}/#{file}"
      )

      source!(root, "#{directory}/#{file}")
    end)

    actual =
      ~w(lib cure test examples)
      |> Enum.flat_map(fn role ->
        Path.wildcard(Path.join([root, directory, role, "**", "*"]), match_dot: true)
      end)
      |> Enum.filter(&File.regular?/1)
      |> Enum.map(&Path.relative_to(&1, Path.join(root, directory)))

    ensure!(MapSet.new(files) == MapSet.new(actual), "unlisted or missing bundle files: #{id}")
    ensure!(is_list(piece["grounding"]) and piece["grounding"] != [], "grounding missing: #{id}")

    ensure!(
      Enum.any?(piece["grounding"], &(&1["kind"] == "test")),
      "executable evidence missing: #{id}"
    )

    Enum.each(piece["grounding"], fn claim ->
      ensure!(claim["kind"] in @grounding, "invalid grounding kind: #{id}")
      nonempty!(claim["claim"], "grounding claim: #{id}")

      case claim["kind"] do
        kind when kind in ~w(proof type test monitor) ->
          ensure!(claim["file"] in files, "evidence outside bundle: #{id}")

          if kind == "test",
            do:
              ensure!(
                String.ends_with?(claim["file"], "_test.exs"),
                "test evidence must be executable: #{id}"
              )

          if kind == "proof" do
            symbol = claim["symbol"]
            nonempty!(symbol, "proof symbol: #{id}")
            source = File.read!(source!(root, "#{directory}/#{claim["file"]}"))

            ensure!(
              equality_declaration?(source, symbol),
              "missing checked equality proof #{symbol}: #{id}"
            )
          end

        "upstream" ->
          ensure!(claim["provider"] in piece["providers"], "undeclared upstream provider: #{id}")

          ensure!(
            is_binary(claim["reference"]) and String.starts_with?(claim["reference"], "https://"),
            "missing upstream reference: #{id}"
          )

        "assumption" ->
          :ok
      end
    end)
  end

  defp validate_operations!(piece) do
    operations = piece["operations"]
    id = piece["id"]

    ensure!(
      is_map(operations) and Enum.sort(Map.keys(operations)) == Enum.sort(@faces),
      "declare telemetry/config/control applicability: #{id}"
    )

    for face <- @faces do
      entry = operations[face]

      ensure!(
        is_map(entry) and entry["status"] in ~w(supported inherited not_applicable planned),
        "invalid #{face} applicability: #{id}"
      )

      nonempty!(entry["contract"], "#{face} contract/reason: #{id}")

      if entry["status"] == "inherited" do
        ensure!(
          entry["from"] in (piece["providers"] ++ piece["dependencies"]),
          "undeclared #{face} inheritance: #{id}"
        )
      else
        ensure!(!Map.has_key?(entry, "from"), "unexpected #{face} inheritance: #{id}")
      end
    end
  end

  # Parse declarations with the pinned Cure parser. Comments and string literals
  # must not count as definitions. Compilation still owns type/proof checking;
  # this only connects a metadata claim to its actual equality declaration.
  defp equality_declaration?(source, symbol) do
    with {:ok, tokens} <- Cure.Compiler.Lexer.tokenize(source, emit_events: false),
         {:ok, ast} <- Cure.Compiler.Parser.parse(tokens, emit_events: false) do
      ast
      |> declarations()
      |> Enum.any?(fn meta ->
        meta[:name] == symbol and
          case meta[:return_type] do
            {:function_call, type_meta, [_, _, _]} -> type_meta[:name] == "Equivalent"
            _ -> false
          end
      end)
    else
      _ -> false
    end
  end

  defp declarations({:function_def, meta, _}), do: [meta]

  defp declarations({kind, _, children}) when kind in [:block, :container],
    do: Enum.flat_map(children, &declarations/1)

  defp declarations(_), do: []

  defp validate_provider!(root, {id, provider}) do
    ensure!(Regex.match?(~r/\A[a-z][a-z0-9_]*\z/, id), "invalid provider ID")
    nonempty!(provider["version"], "provider version: #{id}")
    nonempty!(provider["license"], "provider license: #{id}")

    ensure!(
      String.starts_with?(provider["reference"] || "", "https://"),
      "provider reference: #{id}"
    )

    lock = File.read!(source!(root, "mix.lock"))
    package = provider["package"]

    case provider["source"] do
      "hex" ->
        ensure!(
          is_binary(package) and Regex.match?(~r/\A[a-z][a-z0-9_]*\z/, package),
          "invalid package: #{id}"
        )

        pattern = ~r/"#{Regex.escape(package)}":\s*\{:hex,\s*:#{Regex.escape(package)},\s*"([^"]+)"/

        ensure!(
          Regex.run(pattern, lock, capture: :all_but_first) == [provider["version"]],
          "provider lock mismatch: #{id}"
        )

      "git" ->
        ensure!(
          is_binary(package) and Regex.match?(~r/\A[a-z][a-z0-9_]*\z/, package),
          "invalid package: #{id}"
        )

        ensure!(
          Regex.match?(~r/\A[0-9a-f]{40}\z/, provider["revision"] || ""),
          "git pin missing: #{id}"
        )

        pattern = ~r/"#{Regex.escape(package)}":\s*\{:git,\s*"([^"]+)",\s*"([^"]+)"/

        ensure!(
          Regex.run(pattern, lock, capture: :all_but_first) == [
            provider["url"],
            provider["revision"]
          ],
          "provider lock mismatch: #{id}"
        )

      "platform" ->
        tool = provider["tool"]
        ensure!(tool in ~w(elixir erlang), "invalid platform: #{id}")
        pins = File.read!(source!(root, ".tool-versions"))

        ensure!(
          Regex.match?(~r/^#{tool} #{Regex.escape(provider["version"])}(?:-otp-\d+)?$/m, pins),
          "platform pin mismatch: #{id}"
        )

      _ ->
        fail!("invalid provider source: #{id}")
    end
  end

  defp visit!(registry, id, active, {seen, order}) do
    ensure!(id not in active, "piece dependency cycle: #{Enum.join([id | active], " -> ")}")
    entry = Map.get(registry.entries, id) || fail!("unknown piece dependency: #{id}")
    ensure!(entry["status"] == "ready", "piece is #{entry["status"]}, not consumable: #{id}")

    if MapSet.member?(seen, id) do
      {seen, order}
    else
      {seen, order} =
        Enum.reduce(entry["dependencies"], {seen, order}, fn dependency, acc ->
          visit!(registry, dependency, [id | active], acc)
        end)

      {MapSet.put(seen, id), order ++ [id]}
    end
  end

  defp json!(root, file), do: root |> source!(file) |> File.read!() |> Jason.decode!()
  defp version!(data), do: ensure!(data["schema_version"] == 1, "unsupported registry schema")

  defp id!(id),
    do:
      ensure!(
        is_binary(id) and Regex.match?(~r/\A[a-z][a-z0-9-]*\/[a-z][a-z0-9-]*\z/, id),
        "invalid piece ID: #{inspect(id)}"
      )

  defp nonempty!(value, name),
    do: ensure!(is_binary(value) and String.trim(value) != "", "missing #{name}")

  defp ensure!(true, _), do: :ok
  defp ensure!(_, message), do: fail!(message)
  defp fail!(message), do: raise(ArgumentError, message)
  defp cell(text), do: text |> String.replace("|", "\\|") |> String.replace("\n", " ")
end
